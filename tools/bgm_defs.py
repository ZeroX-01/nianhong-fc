# 5) bgm_tense —— A 羽 + 半音上行，150BPM，10 小节 = 16.0s
#    动机：A2 十六分固定低音踏板 + 每两小节整体升半音的"逼近"动机；
#          打击乐随小节加密加响，循环回到原位 = 又一轮逼近，手心出汗。
# ---------------------------------------------------------------------------
@bgm('bgm_tense', 16.0, 150, 150.0, vol=0.5, key_sig='A 羽 + 半音上行动机')
def _bgm_tense():
    def semi(base, k):
        """把音名升 k 个半音"""
        names = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
        up = base.upper()
        i = 1 if up[1] not in '#' else 2
        pc = names.index(up[:i]) if up[:i] in names else names.index(up[:i].replace('B', '#'))
        octv = int(up[i:])
        idx = pc + k
        return '%s%d' % (names[idx % 12], octv + idx // 12)

    mel = []
    for k in range(5):                     # A -> A# -> B -> C -> C#，越来越近
        r = lambda s, kk=k: semi(s, kk)
        v = 0.72 + 0.07 * k                # 音量逐段推进
        mel += [(r('A4'), .5, v), (r('A4'), .5, v), (r('A#4'), .5, v), (r('A4'), .5, v),
                (r('C5'), 1, v), (r('A#4'), 1, v)]
        mel += [(r('C5'), .5, v), (r('C#5'), .5, v), (r('C5'), .5, v), (r('A#4'), .5, v),
                (r('A4'), 2, v)]
    # 高音"报警"声部：后 6 小节才进来，八分音符交替
    harm = [('r', 4 * 4)]
