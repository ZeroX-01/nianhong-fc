def format_score(sc, bar_beats=4.0, chans=('p1', 'p2', 'tri')):
    """把音序 token 还原成可读乐谱文本（音名+时值，按小节分行）"""
    names = {'p1': '方波1 主旋律', 'p2': '方波2 和声', 'tri': '三角波 贝斯'}
    lines = ['BPM=%.3f  每小节 %g 拍  时长 %.2fs' % (sc['bpm'], bar_beats, sc['dur'])]
    for c in chans:
        seq = sc.get(c)
        if not seq:
            continue
        lines.append('--- %s ---' % names.get(c, c))
        bar, acc, out = 1, 0.0, []
        for tk in seq:
            note, dur = tk[0], tk[1]
            out.append('%s(%g)' % (note if note != 'r' else '休', dur))
            acc += dur
            while acc >= bar_beats - 1e-9:
                lines.append('  第%2d小节 | %s' % (bar, ' '.join(out)))
                bar += 1
                acc -= bar_beats
                out = []
        if out:
            lines.append('  第%2d小节 | %s' % (bar, ' '.join(out)))
    if sc.get('drums'):
        lines.append('--- 噪声 打击乐（每字符=1/16 拍位，K底鼓 S军鼓 s轻军鼓 H镲 h轻镲 C大镲）---')
        for i, b in enumerate(sc['drums']):
            lines.append('  第%2d小节 | %s' % (i + 1, b))
    return '\n'.join(lines)


def bars_to_seq(bars, bar_beats=4.0, name=''):
    """把 [[(note,dur),...], ...] 逐小节展开成音序 token；顺带校验每小节拍数"""
    seq = []
    for i, bar in enumerate(bars):
        s = sum(t[1] for t in bar)
        if abs(s - bar_beats) > 1e-6:
            raise AssertionError('%s 第 %d 小节拍数 = %s（应为 %s）' % (name, i + 1, s, bar_beats))
        seq.extend(bar)
    return seq


# 五声音阶内的"低三度"和声映射（宫调系统 C D E G A）——保证永远协和
_PENT_DOWN = {'C': ('A', -1), 'D': ('C', 0), 'E': ('C', 0),
              'G': ('E', 0), 'A': ('G', 0), 'B': ('G', 0),
              'F': ('D', 0)}


def harm_down3(seq, vol_scale=1.0):
    """把一条旋律映射成五声音阶低三度和声声部"""
    out = []
    for tk in seq:
        note, dur = tk[0], tk[1]
        v = (tk[2] if len(tk) > 2 else 1.0) * vol_scale
        if note in ('r', '~'):
            out.append((note, dur, v))
            continue
        up = note.upper()
        name, octv = up[0], int(up[-1])
        tgt, doct = _PENT_DOWN.get(name, (name, 0))
        out.append(('%s%d' % (tgt, octv + doct), dur, v))
    return out


def comp16(bars_pitches, step=0.25, vol=1.0, rest_mask=None):
    """
    十六分音符伴奏：bars_pitches = [[p1..p16], ...]，None 表示休止。
    """
    seq = []
    for bar in bars_pitches:
        for i, p in enumerate(bar):
            seq.append((p if p else 'r', step, vol))
    return seq


def ostinato(note, bars, per_bar=16, step=0.25, vol=1.0):
    """固定低音：同一个音反复（bgm_tense 的十六分音符踏板）"""
    return [(note, step, vol)] * (bars * per_bar)


def assemble(dur, bpm, p1=None, p2=None, tri=None, drums=None,
             p1_duty=0.5, p2_duty=0.5,
             p1_preset='lead', p2_preset='organ', tri_preset='bass',
             p1_vol=0.85, p2_vol=0.6, tri_vol=0.9, drum_vol=0.7,
             mix=(0.55, 0.30, 0.42, 0.26), vib=None, vib_delay=0.12,
             tail=1.5, loop=True, drum_step=0.25, drum_accents=None,
             pans=None, master=None):
    """
    4 声部渲染 + 循环折叠 + 轻立体声。
    mix = (p1, p2, tri, noise) 各声部混音增益。
    无缝循环：多渲染 `tail` 秒尾巴，再用 wrap_fold 折回开头 —— 循环点零跳变。
    """
    global LAST_SCORE
    LAST_SCORE = dict(bpm=bpm, dur=dur, p1=p1, p2=p2, tri=tri, drums=drums,
                      p1_duty=p1_duty, p2_duty=p2_duty)
    loop_n = ns(dur)
    total = loop_n + ns(tail)
    ch = {}
    ch['p1'] = (render_pulse(parse_seq(p1, bpm), total, duty=p1_duty, vol=p1_vol,
                             preset=p1_preset, vib=vib, vib_delay=vib_delay)
                if p1 else np.zeros(total))
    ch['p2'] = (render_pulse(parse_seq(p2, bpm), total, duty=p2_duty, vol=p2_vol,
                             preset=p2_preset)
                if p2 else np.zeros(total))
    ch['tri'] = (render_tri(parse_seq(tri, bpm), total, vol=tri_vol, preset=tri_preset)
                 if tri else np.zeros(total))
    ch['noi'] = (render_drums(drums, total, bpm, vol=drum_vol, step=drum_step,
                              accents=drum_accents)
                 if drums else np.zeros(total))
    g = {'p1': mix[0], 'p2': mix[1], 'tri': mix[2], 'noi': mix[3]}
    for k in ch:
        ch[k] = ch[k] * g[k]
        ch[k] = wrap_fold(ch[k], loop_n) if loop else ch[k][:loop_n]
    st = mix_stereo(ch, pans=pans)
    if master is not None:
        st = st * master
    return st


